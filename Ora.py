import turtle

turtle.pencolor("blue")
turtle.goto(0, 100)
turtle.forward(10)
turtle.right(90)
turtle.forward(100)
turtle.right(90)
turtle.forward(10)

turtle.penup()
turtle.goto(0, 0)
turtle.pendown()

turtle.pencolor("red")
turtle.left(-130)
turtle.forward(100)
turtle.right(90)
turtle.forward(10)
turtle.right(90)
turtle.forward(100)


turtle.done()